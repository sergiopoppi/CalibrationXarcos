"""Calibrate XARCOS CLASS spectra to Jy.

For every spectrum the following factors are applied:

1. opacity:     exp(tau / sin(el))   -> Ta*
2. gain curve:  1 / gain_curve(el)
3. gain:        1 / gain(t)          -> Jy

tau and gain are linearly interpolated in time from the input tables.
By default the three factors are combined into a single ``mul`` per
spectrum; ``--keep-intermediate`` writes the stepwise files instead.
"""

import argparse
import logging
import math
import os
import sys

from pyclass import comm, gdict

from calibration_core import (
    DEFAULT_MAX_DT_DAYS,
    DEFAULT_MIN_ELEVATION_DEG,
    gain_curve,
    interpolate,
    opacity_factor,
    polarization_from_line,
    read_table,
    scan_mjd,
)

log = logging.getLogger("calibrate_jy")


class Scan(object):
    """Header values of the spectrum currently loaded in CLASS."""

    def __init__(self):
        self.number = int(gdict.r.head.gen.num)
        self.el_rad = float(gdict.elevation)
        self.el_deg = math.degrees(self.el_rad)
        self.mjd = scan_mjd(float(gdict.r.head.gen.dobs), float(gdict.r.head.gen.ut))
        self.polarization = polarization_from_line(gdict.line)


def run_pass(file_in, file_out, factor_fn, min_elevation):
    """Multiply every spectrum of ``file_in`` by ``factor_fn(scan)``."""
    log.info("%s -> %s", file_in, file_out)
    comm("file in " + file_in)
    comm("file out " + file_out + " single /overwrite")
    comm("find")
    found = int(gdict.found)
    written = skipped = 0
    for _ in range(found):
        comm("get next")
        scan = Scan()
        if scan.el_deg < min_elevation:
            log.warning("obs %d: elevation %.2f deg below %.2f, skipped",
                        scan.number, scan.el_deg, min_elevation)
            skipped += 1
            continue
        coeff = factor_fn(scan)
        log.debug("obs %d %s el=%.2f mjd=%.5f mul %.6g",
                  scan.number, scan.polarization, scan.el_deg, scan.mjd, coeff)
        comm("mul %.10g" % coeff)
        comm("write")
        written += 1
    log.info("%d spectra written, %d skipped", written, skipped)


def calibrate(file_in, taufile, gainfile, keep_intermediate=False,
              max_dt=DEFAULT_MAX_DT_DAYS, min_elevation=DEFAULT_MIN_ELEVATION_DEG):
    tau_table = read_table(taufile)
    gain_table = read_table(gainfile)

    def opacity(scan):
        tau = interpolate(tau_table, scan.mjd, scan.polarization, max_dt, "tau")
        return opacity_factor(tau, scan.el_rad)

    def elevation_gain(scan):
        return 1.0 / gain_curve(scan.el_deg)

    def flux_gain(scan):
        return 1.0 / interpolate(gain_table, scan.mjd, scan.polarization, max_dt, "gain")

    base = os.path.splitext(file_in)[0]
    tstar = base + "_tstar.med"
    tstar_gain = base + "_tstar_gain.med"
    final = base + "_tstar_gain_jy.med"

    if keep_intermediate:
        run_pass(file_in, tstar, opacity, min_elevation)
        run_pass(tstar, tstar_gain, elevation_gain, min_elevation)
        run_pass(tstar_gain, final, flux_gain, min_elevation)
    else:
        run_pass(file_in, final,
                 lambda s: opacity(s) * elevation_gain(s) * flux_gain(s),
                 min_elevation)
    return final


def parse_args(argv):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("classfile", help="CLASS file generated by discos2class")
    p.add_argument("taufile", help="opacity table: MJD tau_LCP tau_RCP")
    p.add_argument("gainfile", help="gain table: MJD gain_LCP gain_RCP")
    p.add_argument("--keep-intermediate", action="store_true",
                   help="write _tstar and _tstar_gain files (three passes)")
    p.add_argument("--max-dt", type=float, default=DEFAULT_MAX_DT_DAYS,
                   help="warn if the closest tau/gain sample is farther than "
                        "this many days (default %(default)s)")
    p.add_argument("--min-elevation", type=float, default=DEFAULT_MIN_ELEVATION_DEG,
                   help="skip spectra below this elevation in degrees "
                        "(default %(default)s)")
    p.add_argument("-v", "--verbose", action="store_true",
                   help="log the factor applied to every spectrum")
    return p.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(levelname)s: %(message)s")
    out = calibrate(args.classfile, args.taufile, args.gainfile,
                    keep_intermediate=args.keep_intermediate,
                    max_dt=args.max_dt, min_elevation=args.min_elevation)
    log.info("output: %s", out)


if __name__ == "__main__":
    main(sys.argv[1:])
